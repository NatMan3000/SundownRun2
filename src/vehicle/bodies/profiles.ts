// ============================================================
//  BODY PROFILES - the five car shapes, as numbers
// ------------------------------------------------------------
//  Every car is built the same way (bodies/build.ts): a row of
//  cross-sections ("stations") from nose to tail, joined into one
//  faceted hull - like a paper model, which is what gives these
//  cars their crisp, crystal-cut neon look. A glass canopy is
//  lofted the same way and sits in the hull. Lights, fins and trim
//  are added on top.
//
//  CAR SPACE (metres): +Z forward (nose), +Y up, +X the car's LEFT.
//  The road is at y = -0.542 when the car sits at rest.
//  The wheels are shared by every body and never move:
//    centres at x = +/-0.80, z = +/-1.42, y = -0.20, radius 0.35,
//    0.28 wide (so a tyre fills x 0.66..0.94 and its top is y 0.15).
//  Any station within 0.42 m of a wheel centre (along z) must keep
//  the lower hull inside x 0.62 and the shoulder above y 0.18, or
//  the paint swallows the tyre.
//
//  A hull station is ten numbers, one half of the cross-section
//  (mirrored to make the other side):
//    [ z,  yBot, wBot,  yMid, wMid,  ySh, wSh,  yTop, wTop,  yCrown ]
//      z            where along the car
//      yBot / wBot  underside height and half-width
//      yMid / wMid  lower flank (pinched in over the wheels)
//      ySh  / wSh   the shoulder - the widest line, where the light strip runs
//      yTop / wTop  the deck edge
//      yCrown       height on the centre line
//
//  A canopy station is five numbers: [ z, yBase, wBase, yTop, wTop ].
// ============================================================

import type { BodyId } from './catalog'

export interface BoxPart {
  /** Size. */
  w: number
  h: number
  d: number
  /** Centre (x mirrored when `mirror` is true). */
  x: number
  y: number
  z: number
  /** Tilt about the car's x axis, radians (+ = front edge up). */
  rx?: number
  /** Also place a copy at -x. */
  mirror?: boolean
}

export interface LightBar {
  z: number
  y: number
  /** Half-width of the bar across the car. */
  halfW: number
  /** Bar height. */
  h: number
}

export interface LiveryStrip {
  /** Which profile point it follows: 3 = shoulder, 4 = deck edge. */
  point: 3 | 4
  zFrom: number
  zTo: number
  /** Strip height in metres. */
  width: number
}

export interface BodyProfile {
  hull: number[][]
  canopy: number[][]
  livery: LiveryStrip[]
  head: LightBar
  tail: LightBar
  /** Painted extras: wings, fins, roof plates. */
  paint: BoxPart[]
  /** Dark trim: splitters, diffusers, skirts. */
  trim: BoxPart[]
  /** Extra glowing details (livery colour): wing edges, fin edges. */
  glow: BoxPart[]
}

